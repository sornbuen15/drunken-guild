#!/usr/bin/env python3
"""Fail the build when a skill or agent file grows past the size standard.

DG-516. The Boss's rule: skills and agents must be light, not long — a long
file costs context on every load and gets skimmed, not followed. The
standard itself lives once, in ``.claude/rules/ai-layer.md``: a ``SKILL.md``
stays at or under :data:`SKILL_LIMIT` lines, an agent file at or under
:data:`AGENT_LIMIT`. This script is the guard, not a second copy of the rule.

Today's oversize files did not get rewritten to pass this — that is a
separate, follow-up change, ordered by size in the PR that added this
check. Instead a checked-in baseline (:data:`BASELINE_PATH`) names each one
and the line count it was measured at, and acts as a ratchet: that file may
shrink freely, but the moment it is *at or under* the file's own line limit
it is compliant again like any other, and the moment it grows past the
baseline's recorded count, this fails. A file absent from the baseline gets
no slack: new work is held to the limit from the start.

**Deliberately dumb**, in the same sense ``check_doc_drift.py`` is: no
attempt to parse prose and judge whether a file "needs" its length, just a
line count against a recorded one. The discipline it depends on is small:
the PR that shrinks an oversize file lowers its baseline entry (or removes
it, once compliant), and the PR that discovers a new one some other way
does not get to add slack for it here.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

#: A `SKILL.md` body stays under this many lines; detail beyond it moves to a
#: references/ file read on demand. Written once in `.claude/rules/ai-layer.md`.
SKILL_LIMIT = 120

#: An agent file stays under this many lines. Same rule, same file.
AGENT_LIMIT = 100

#: Today's oversize files, and the line count each was measured at when this
#: check was added or last tightened. A ratchet: the recorded count may only
#: go down, never up — see the module docstring.
BASELINE_FILENAME = "skill_size_baseline.json"

#: Not source to measure. `.claude/worktrees` and `build/` hold either whole
#: copies of this repository at older commits or packaging output, neither
#: authored here by hand.
SKIPPED_DIRS = frozenset(
    {
        ".venv",
        ".git",
        "node_modules",
        "build",
        "not_use",
        ".claude",
        ".mypy_cache",
        "__pycache__",
    }
)

#: Generated by the install scripts, never authored by hand (see
#: `.claude/rules/ai-layer.md`, "Read the index before loading a skill") — a
#: list of every agent's name is not itself an agent, and must not be
#: measured against `AGENT_LIMIT`.
AGENT_INDEX_NAME = "INDEX.md"


def _relative_parts(path: Path) -> tuple[str, ...]:
    return path.relative_to(REPO_ROOT).parts


def _skipped(path: Path) -> bool:
    """Only the top-level component is checked, not every part — `build/`
    at the repository root is packaging output, but `skills/flow/build/`
    is a real skill named "build", and a full-parts check skipped it."""
    parts = _relative_parts(path)
    return bool(parts) and parts[0] in SKIPPED_DIRS


def skill_files() -> list[Path]:
    """Every `SKILL.md` in the tree, wherever it lives — `skills/` or a
    plugin's own `skills/` directory both count."""
    return sorted(p for p in REPO_ROOT.rglob("SKILL.md") if not _skipped(p))


def agent_files() -> list[Path]:
    """Every agent file: a `*.md` anywhere under a directory named `agents`,
    at any depth, excluding the generated index.

    `rglob("agents/*.md")` only matched a file directly inside a directory
    literally named `agents` — a file one level deeper, such as
    `agents/nested/huge.md`, never matched the pattern at all and was
    silently never checked, however long it grew (found in review of the
    PR that added this check)."""
    found = []
    for p in REPO_ROOT.rglob("*.md"):
        if _skipped(p) or p.name == AGENT_INDEX_NAME:
            continue
        parts = _relative_parts(p)
        if "agents" in parts[:-1]:
            found.append(p)
    return sorted(found)


def limit_for(path: Path) -> int:
    """The line limit that applies to `path`, by what kind of file it is."""
    return SKILL_LIMIT if path.name == "SKILL.md" else AGENT_LIMIT


def line_count(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def load_baseline() -> dict[str, int]:
    """The checked-in ratchet, keyed by path relative to `REPO_ROOT` with
    forward slashes, since the baseline file travels with the repository and
    must read the same on every platform it is committed from."""
    baseline_path = REPO_ROOT / "scripts" / BASELINE_FILENAME
    if not baseline_path.is_file():
        return {}
    data = json.loads(baseline_path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{baseline_path} must contain a JSON object")
    return {str(key): int(value) for key, value in data.items()}


def scan() -> list[str]:
    baseline = load_baseline()
    seen: set[str] = set()
    problems: list[str] = []

    for path in [*skill_files(), *agent_files()]:
        relative = path.relative_to(REPO_ROOT).as_posix()
        seen.add(relative)
        limit = limit_for(path)
        actual = line_count(path)
        recorded = baseline.get(relative)

        if recorded is None:
            if actual > limit:
                problems.append(
                    f"{relative}: {actual} lines, over the {limit}-line limit "
                    "and not in the baseline. Either bring it under the limit "
                    f"or add it to {BASELINE_FILENAME} as a new, deliberate "
                    "exception."
                )
            continue

        if actual > recorded:
            problems.append(
                f"{relative}: grew to {actual} lines, past the {recorded} the "
                f"baseline recorded. The baseline in {BASELINE_FILENAME} is a "
                "ratchet — it may only shrink."
            )

    stale = sorted(set(baseline) - seen)
    for relative in stale:
        problems.append(
            f"{relative}: listed in {BASELINE_FILENAME} but no longer exists. "
            "Remove the stale entry."
        )

    return problems


def main() -> int:
    problems = scan()
    if not problems:
        total = len(skill_files()) + len(agent_files())
        print(f"[check_skill_size] {total} files checked, none over their baseline.")
        return 0

    print("Skill or agent files grew past the size standard:\n", file=sys.stderr)
    for problem in problems:
        print(f"  {problem}", file=sys.stderr)
    print(
        "\nSee .claude/rules/ai-layer.md for the standard, and "
        f"scripts/{BASELINE_FILENAME} for today's recorded exceptions.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
